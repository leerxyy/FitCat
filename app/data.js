export function recipeNutrition(recipe) {
  const result = { kcal: 0, protein: 0, fat: 0, carbs: 0, weight: 0 };
  for (const [id, weight] of recipe.ingredients) {
    const item = PRODUCTS.find(p => p.id === id);
    result.weight += weight;
    for (const key of ['kcal', 'protein', 'fat', 'carbs']) result[key] += item[key] * weight / 100;
  }
  return Object.fromEntries(Object.entries(result).map(([k, v]) => [k, Math.round(v * 10) / 10]));
}
